//operadores de asignación, incremento y decremento

let a = 1;

document.write("Valor de a: ", a);
document.write("<br>");
a++;//aumenta valor en 1
document.write("Valor de a: ", a);
document.write("<br>");
a+=5;//aumento variable que deseamos
document.write("Valor de a: ", a);
document.write("<br>");
a--;//resta valor en 1
document.write("Valor de a: ", a);
document.write("<br>");
a-=3;//resta variable
document.write("Valor de a: ", a);
document.write("<br>");
a*=2;//multiplica la variable
document.write("Valor de a: ", a);
document.write("<br>");
a/=3;//divide la variable 
document.write("Valor de a: ", a);
document.write("<br>");
a**=2;//potencializa la variable
document.write("Valor de a: ", a);